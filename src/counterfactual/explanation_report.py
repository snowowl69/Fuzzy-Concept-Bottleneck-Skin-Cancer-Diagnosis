"""Explanation Report Generator.

Assembles structured, human-readable explanation reports combining:
- Original image metadata
- Segmentation summary
- Extracted geometric features
- Fuzzy ABCDE concept scores with plain-language interpretation
- Diagnosis prediction with class probabilities
- Intervention results (if any)
- Counterfactual explanation text and concept changes
- Research prototype disclaimer
"""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any, Dict, List, Optional


# -- Concept Interpretation Thresholds --
_LEVEL_THRESHOLDS = {"low": 0.33, "moderate": 0.66}


def _interpret_concept_value(concept_name: str, value: float) -> str:
    """Convert a continuous concept membership value to a plain-language interpretation."""
    if value <= _LEVEL_THRESHOLDS["low"]:
        level = "low"
    elif value <= _LEVEL_THRESHOLDS["moderate"]:
        level = "moderate"
    else:
        level = "high"

    interpretation_map = {
        "Asymmetry Score": {
            "low": "The lesion shape is approximately symmetric across both axes.",
            "moderate": "The lesion shows moderate shape asymmetry.",
            "high": "The lesion is strongly asymmetric, a potential indicator of malignancy.",
        },
        "Border Irregularity Score": {
            "low": "The lesion border is smooth and regular.",
            "moderate": "The lesion border shows some irregularity.",
            "high": "The lesion border is highly irregular or ragged.",
        },
        "Color Variation Score": {
            "low": "The lesion color is relatively homogeneous.",
            "moderate": "The lesion shows moderate color variation.",
            "high": "The lesion contains multiple distinct colors or significant variation.",
        },
        "Diameter Score": {
            "low": "The lesion diameter is relatively small.",
            "moderate": "The lesion has a moderate diameter.",
            "high": "The lesion is large in diameter, which may warrant attention.",
        },
    }

    concept_interps = interpretation_map.get(concept_name, {})
    return concept_interps.get(level, f"{concept_name} is {level} ({value:.2f}).")


class ExplanationReport:
    """Structured explanation report for a single skin lesion analysis."""

    def __init__(self):
        self.report_id: str = ""
        self.timestamp: str = ""
        self.image_metadata: Dict[str, Any] = {}
        self.segmentation_summary: Dict[str, Any] = {}
        self.extracted_features: Dict[str, float] = {}
        self.fuzzy_concepts: Dict[str, float] = {}
        self.concept_interpretations: Dict[str, str] = {}
        self.diagnosis: Dict[str, Any] = {}
        self.intervention: Optional[Dict[str, Any]] = None
        self.counterfactual: Optional[Dict[str, Any]] = None
        self.disclaimer: str = (
            "RESEARCH PROTOTYPE ONLY: This report is generated by an experimental "
            "AI model for investigational purposes only. It is NOT approved or "
            "cleared for primary clinical diagnosis. All findings must be "
            "validated by a certified dermatologist or pathologist."
        )

    def populate(
        self,
        prediction_result: Dict[str, Any],
        image_shape: tuple = None,
        mask_area_fraction: float = None,
        intervention_result: Optional[Dict[str, Any]] = None,
        counterfactual_result: Optional[Dict[str, Any]] = None,
    ) -> "ExplanationReport":
        """Populate the report from prediction pipeline outputs.

        Args:
            prediction_result: Output from FuzzyConceptBottleneckModel.predict_image()
            image_shape: (H, W, C) of the original image
            mask_area_fraction: Fraction of image covered by lesion mask
            intervention_result: Output from ConceptInterventionEngine (if any)
            counterfactual_result: Output from CounterfactualGenerator (if any)

        Returns:
            Self for chaining.
        """
        import uuid

        self.report_id = f"RPT-{datetime.utcnow().strftime('%Y%m%d%H%M%S')}-{uuid.uuid4().hex[:6].upper()}"
        self.timestamp = datetime.utcnow().isoformat() + "Z"

        # Image metadata
        if image_shape:
            self.image_metadata = {
                "height": image_shape[0],
                "width": image_shape[1],
                "channels": image_shape[2] if len(image_shape) > 2 else 1,
            }

        # Segmentation
        self.segmentation_summary = {
            "lesion_area_fraction": mask_area_fraction or 0.0,
            "segmentation_method": "U-Net (primary) / Otsu threshold (fallback)",
        }

        # Features
        self.extracted_features = prediction_result.get("extracted_features", {})

        # Fuzzy concepts
        self.fuzzy_concepts = prediction_result.get("fuzzy_concepts", {})
        self.concept_interpretations = {
            name: _interpret_concept_value(name, val)
            for name, val in self.fuzzy_concepts.items()
        }

        # Diagnosis
        self.diagnosis = {
            "predicted_class": prediction_result.get("predicted_class_name", "Unknown"),
            "confidence": prediction_result.get("confidence", 0.0),
            "class_probabilities": prediction_result.get("class_probabilities", {}),
        }

        # Intervention
        if intervention_result:
            self.intervention = intervention_result

        # Counterfactual
        if counterfactual_result:
            self.counterfactual = counterfactual_result

        return self

    def generate_text_report(self) -> str:
        """Generate a human-readable markdown text report.

        Returns:
            Multi-line string with structured explanation.
        """
        lines = []
        lines.append("# Clinical Diagnostic Summary Report")
        lines.append(f"**Report ID:** {self.report_id}")
        lines.append(f"**Generated:** {self.timestamp}")
        lines.append(f"**System:** Fuzzy Concept-Bottleneck Skin Cancer Diagnosis")
        lines.append("")

        # Diagnosis
        lines.append("## Diagnosis Prediction")
        lines.append(f"- **Predicted Class:** {self.diagnosis.get('predicted_class', 'N/A')}")
        lines.append(f"- **Confidence:** {self.diagnosis.get('confidence', 0.0)*100:.1f}%")
        lines.append("")

        if self.diagnosis.get("class_probabilities"):
            lines.append("### Class Probabilities")
            for cls, prob in sorted(self.diagnosis["class_probabilities"].items(),
                                     key=lambda x: x[1], reverse=True):
                bar = "█" * int(prob * 20) + "░" * (20 - int(prob * 20))
                lines.append(f"- {cls}: {prob*100:.1f}% {bar}")
            lines.append("")

        # Fuzzy Concepts
        lines.append("## Fuzzy ABCDE Concept Scores")
        for name, val in self.fuzzy_concepts.items():
            interp = self.concept_interpretations.get(name, "")
            lines.append(f"- **{name}:** {val:.3f}")
            lines.append(f"  > {interp}")
        lines.append("")

        # Extracted Features
        if self.extracted_features:
            lines.append("## Extracted Geometric Features")
            for fname, fval in self.extracted_features.items():
                if isinstance(fval, float):
                    lines.append(f"- {fname}: {fval:.4f}")
                else:
                    lines.append(f"- {fname}: {fval}")
            lines.append("")

        # Intervention
        if self.intervention:
            lines.append("## Concept Intervention Results")
            lines.append(f"- **Original Diagnosis:** {self.intervention.get('original_diagnosis', 'N/A')}")
            lines.append(f"- **After Intervention:** {self.intervention.get('intervened_diagnosis', 'N/A')}")
            flipped = self.intervention.get('diagnosis_flipped', False)
            lines.append(f"- **Diagnosis Changed:** {'Yes' if flipped else 'No'}")
            lines.append("")

        # Counterfactual
        if self.counterfactual:
            lines.append("## Counterfactual Explanation")
            lines.append(f"- **Target Class:** {self.counterfactual.get('target_class_name', 'N/A')}")
            lines.append(f"- **Success:** {self.counterfactual.get('success', False)}")
            explanation = self.counterfactual.get('explanation_text', '')
            if explanation:
                lines.append(f"\n> {explanation}")
            lines.append("")

        # Disclaimer
        lines.append("---")
        lines.append(f"⚠️ **{self.disclaimer}**")

        return "\n".join(lines)

    def generate_structured_report(self) -> Dict[str, Any]:
        """Generate a JSON-serializable structured report.

        Returns:
            Dictionary with all report fields.
        """
        return {
            "report_id": self.report_id,
            "timestamp": self.timestamp,
            "system": "Fuzzy Concept-Bottleneck Skin Cancer Diagnosis v2.0",
            "image_metadata": self.image_metadata,
            "segmentation_summary": self.segmentation_summary,
            "extracted_features": self.extracted_features,
            "fuzzy_concepts": self.fuzzy_concepts,
            "concept_interpretations": self.concept_interpretations,
            "diagnosis": self.diagnosis,
            "intervention": self.intervention,
            "counterfactual": self.counterfactual,
            "disclaimer": self.disclaimer,
        }

    def save_json(self, filepath: str) -> None:
        """Save structured report as JSON file."""
        report = self.generate_structured_report()
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, default=str)
